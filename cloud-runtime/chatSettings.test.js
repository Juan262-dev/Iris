import assert from 'node:assert/strict';
import { decideCommand } from './chatSettings.js';
const group = { jid: 'test@g.us', fromMe: false, enabled: false };
const run = (text, props = {}) => decideCommand({ ...group, ...props, text });
assert.equal(run(':on'), null);
assert.equal(run(':on', { fromMe: true }), 'on');
assert.equal(run(':off', { fromMe: true }), 'off');
assert.equal(run(':off', { enabled: true }), null);
assert.equal(run(':ping'), null);
assert.equal(run(':ping', { enabled: true, fromMe: true }), 'ping');
assert.equal(run(':ping', { enabled: true }), 'ping');
assert.equal(run(':menu', { enabled: true }), 'menu');
assert.equal(run(':status', { enabled: true }), 'status');
assert.equal(run('!ajuda', { enabled: true }), null);
assert.equal(run(':on', { jid: 'test@s.whatsapp.net', fromMe: true }), null);
assert.equal(run(':on', { jid: 'status@broadcast', fromMe: true }), null);
assert.equal(run('!iris on',{fromMe:true}),null);
assert.equal(run('!ping',{enabled:true}),null);
assert.equal(run('!iris off',{fromMe:true,enabled:true}),null);
console.log('Iris: group opt-in command tests passed');
