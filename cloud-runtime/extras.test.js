import assert from 'node:assert/strict';
import { makeExtras, makeLimiter } from './extras.js';
import { menu, parseExtra } from './features.js';
let time=100;
const allow=makeLimiter({windowMs:1000,max:2,groupMax:3,now:()=>time});
assert.equal(allow('g','a'),true);
assert.equal(allow('g','a'),true);
assert.equal(allow('g','a'),false);
assert.equal(allow('g','b'),true);
assert.equal(allow('g','b'),false);
time+=1000;
assert.equal(allow('g','a'),true);
const extras=makeExtras();
const g={jid:'g',actor:'a',name:'numero'};
assert.match(extras({...g,arg:''}),/8 tentativas/);
assert.match(extras({...g,arg:'101'}),/Escolha/);
assert.match(extras({...g,actor:'b',arg:'1'}),/começar/);
assert.match(extras({...g,arg:'sair'}),/encerrado/);
assert.match(extras({...g,name:'ppt',arg:'pedra'}),/Você: pedra/);
assert.match(menu('jogos'),/numero/);
assert.doesNotMatch(menu('jogos'),/ECONOMIA VIRTUAL/);
assert.match(menu(''),/Sem IA externa/);
assert.equal(parseExtra(':ppt pedra',false).name,'ppt');
console.log('Iris: menu, mini games and anti-spam tests passed');
