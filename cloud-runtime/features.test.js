import assert from 'node:assert/strict';
import { parseExtra, menu } from './features.js';
assert.equal(parseExtra(':fechar',false),null);
assert.equal(parseExtra(':criar teste texto',false),null);
assert.deepEqual(parseExtra(':criar teste Texto',true),{name:'criar',arg:'teste Texto'});
assert.deepEqual(parseExtra(':resposta 2',false),{name:'resposta',arg:'2'});
assert.deepEqual(parseExtra(':s',false),{name:'s',arg:''});
assert.equal(parseExtra('!ping',true),null);
assert.deepEqual(parseExtra(':ping',true),{name:'ping',arg:''});
assert.equal(parseExtra('!s',false),null);
assert.equal(parseExtra('!iris menu',true),null);
assert.equal(parseExtra('.menu',true),null);
assert.deepEqual(parseExtra(':fig',false),{name:'s',arg:''});
assert.equal(parseExtra(':desconhecido',true),null);
assert.ok(menu().includes(':'));
console.log('Iris: expanded command parser tests passed');
