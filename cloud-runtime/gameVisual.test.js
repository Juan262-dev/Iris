import assert from 'node:assert/strict';
import sharp from 'sharp';
import {dominoHand,dominoTable,memoryBoard,ludoVisual,stopForm,gameNotice} from './gameVisual.js';
import {parseStopQuote,stopPrompt,makeStopTickets} from './stopPrivate.js';
const a='a',b='b';
const dom={ids:[a,b],turn:0,hands:{a:[[2,3],[0,0]],b:[[6,5]]},deck:[[1,2]],chain:[[1,2]]};
const board=await dominoTable(dom,'Mesa pública');
const privateA=await dominoHand(dom,a,{'2-3':1,'0-0':2},'Suas peças');
const privateB=await dominoHand(dom,b,{'5-6':1},'Suas peças');
const info=await sharp(board.image).metadata();assert.equal(info.format,'png');assert.equal(info.width,720);
assert.notDeepEqual(privateA.image,privateB.image);
const changed={...dom,hands:{a:[[0,6],[4,4]],b:[[2,2]]}};
assert.deepEqual(board.image,(await dominoTable(changed,'Mesa pública')).image);
const mem={ids:[a,b],found:[],tries:0,cards:['A','A','B','B','C','C','D','D','E','E','F','F']};
const hidden=await memoryBoard(mem),other=await memoryBoard({...mem,cards:mem.cards.slice().reverse()});
assert.deepEqual(hidden.image,other.image);
assert.notDeepEqual(hidden.image,(await memoryBoard(mem,[0,1])).image);
const ludo={ids:[a,b],pieces:{a:[0,39],b:[-1,40]},turn:0,roll:1};
assert.equal((await sharp((await ludoVisual(ludo,'Ludo')).image).metadata()).width,720);
const form={round:1,letter:'m',categories:['Nome','Animal','Fruta','Cor','Cidade','Objeto','Profissão']};
const prompt=stopPrompt(form),photo=await stopForm(form,prompt);
assert.equal((await sharp(photo.image).metadata()).format,'png');assert.equal(photo.caption,prompt);
const tickets=makeStopTickets({clock:()=>0}),code=tickets.issue({jid:'g',actor:a});tickets.bind(code,'photo-id');
const quote=parseStopQuote({extendedTextMessage:{text:'Maria\nMacaco\nManga',contextInfo:{stanzaId:'photo-id',quotedMessage:{imageMessage:{caption:prompt}}}}});
assert.equal(tickets.quoted(quote.messageId).code,code);
assert.equal((await sharp((await gameNotice('STOP','x'.repeat(300)+'\n< & >')).image).metadata()).width,720);
console.log('Iris: visual game PNGs, concealed cards, private domino isolation and STOP photo quoting tests passed');
