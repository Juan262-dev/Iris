import assert from 'node:assert/strict';
import {inboundMessage,acceptUpsert} from './inbound7.js';
const now=1700000000000,ctx={enabled:true,openedAt:now-10000,now};
const msg={key:{remoteJid:'test@g.us',id:'123',fromMe:true},messageTimestamp:now/1000,message:{conversation:':ping'}};
assert.equal(acceptUpsert('notify',msg,ctx),true);
assert.equal(acceptUpsert('append',msg,ctx),true);
for(const text of [':menu',':status',':diagnostico'])assert.equal(acceptUpsert('append',{...msg,message:{conversation:text}},ctx),true);
for(const text of [':on',':off',':domino novo',':rebaixar','4','mensagem comum'])assert.equal(acceptUpsert('append',{...msg,message:{conversation:text}},ctx),false);
assert.equal(acceptUpsert('append',msg,{...ctx,enabled:false}),false);
assert.equal(acceptUpsert('append',{...msg,key:{...msg.key,fromMe:false}},ctx),false);
assert.equal(acceptUpsert('append',{...msg,key:{...msg.key,remoteJid:'1@s.whatsapp.net'}},ctx),false);
assert.equal(acceptUpsert('append',{...msg,messageTimestamp:now/1000-60},ctx),false);
assert.equal(acceptUpsert('append',msg,{...ctx,openedAt:now+2000}),false);
const wrapped=inboundMessage({...msg,message:{ephemeralMessage:{message:{extendedTextMessage:{text:':ping'}}}}});
assert.equal(wrapped.message.extendedTextMessage.text,':ping');
assert.equal(acceptUpsert('append',wrapped,ctx),true);
const dev=inboundMessage({...msg,message:{deviceSentMessage:{destinationJid:'test@g.us',message:{conversation:':menu'}}}});
assert.equal(dev.message.conversation,':menu');
const forged=inboundMessage({...msg,message:{deviceSentMessage:{destinationJid:'other@g.us',message:{conversation:':menu'}}}});
assert.equal(acceptUpsert('append',forged,ctx),false);
console.log('Iris: inbound wrapped diagnostics, fresh owner append and replay restrictions tests passed');
