import assert from 'node:assert/strict';
import { localReply, winner, makeLocalGames, purchase } from './localFun.js';
import { parseExtra } from './features.js';
assert.match(localReply('Olá'),/resposta local/);
assert.match(localReply(''),/sem IA/);
assert.equal(winner(['X','X','X','','','','','','']),'X');
assert.equal(winner(Array(9).fill('')),null);
const g=makeLocalGames();
const a={jid:'test@g.us',actor:'a',name:'velha'};
assert.match(g({...a,arg:''}),/Jogo da velha/);
assert.match(g({...a,arg:'0'}),/casa livre/);
assert.match(g({...a,actor:'b',arg:'1'}),/começar/);
assert.match(g({...a,arg:'1'}),/Sua vez/);
assert.match(g({...a,name:'forca',arg:''}),/Adivinhe/);
assert.match(g({...a,name:'forca',arg:'ab'}),/Palavra incorreta|Você acertou/);
const p={coins:40,xp:0};
assert.equal(purchase(p,'estrela'),null);
assert.equal(p.coins,20);
assert.match(purchase(p,'estrela'),/já possui/);
assert.match(purchase(p,'trofeu'),/insuficientes/);
assert.equal(parseExtra(':ia perguntar teste',true).name,'ia');
assert.equal(parseExtra(':definirregras teste',false),null);
console.log('Iris: local dialogue, games and shop tests passed');
