import assert from 'node:assert/strict';
import { Chess } from 'chess.js';
import { makeChess, boardText, mission, welcomeMessage } from './nextFeatures.js';
import { parseExtra, menu } from './features.js';
import { makeTextSticker } from './sticker.js';
import sharp from 'sharp';
const play=makeChess({choose:()=>0});
const a={jid:'test@g.us',actor:'a'};
assert.match(play({...a,arg:''}),/brancas/);
assert.match(play({...a,arg:'e2e5'}),/inválida/);
assert.match(play({...a,arg:'e2e4'}),/Íris jogou:/);
assert.match(play({...a,actor:'b',arg:'e2e4'}),/iniciar/);
assert.match(play({...a,arg:'sair'}),/encerrada/);
assert.match(boardText(new Chess()),/a  b  c  d/);
const p={coins:0,xp:3};
assert.equal(mission(p,'primeiros').changed,true);
assert.equal(p.coins,15);
assert.equal(mission(p,'primeiros').changed,false);
assert.equal(p.coins,15);
assert.equal(mission(p,'aprendiz').changed,false);
assert.equal(mission(p,'colecao').changed,false);
assert.match(welcomeMessage('add',1),/Boas-vindas/);
assert.match(welcomeMessage('remove',2),/Até mais/);
assert.equal(welcomeMessage('promote',1),null);
assert.equal(welcomeMessage('add',0),null);
assert.equal(parseExtra('!iris boasvindas on',false),null);
assert.equal(parseExtra('!iris boasvindas on',true).name,'boasvindas');
assert.match(menu('jogos'),/xadrez/);
assert.match(menu('midia'),/texto/);
const sticker=await makeTextSticker('Olá <&> Íris');
assert.ok(sticker.sticker);
const m=await sharp(sticker.sticker).metadata();
assert.equal(m.width,512);
assert.equal(m.height,512);
assert.equal(m.format,'webp');
assert.match(await makeTextSticker('a'.repeat(61)),/60 caracteres/);
console.log('Iris: chess, missions, welcome and text sticker tests passed');
