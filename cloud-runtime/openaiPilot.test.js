import assert from 'node:assert/strict';
import { createAI, aiIntent, configured, configIssue, likelyPrivate, safeModeration } from './openaiPilot.js';
import { parseExtra } from './features.js';
assert.equal(aiIntent('oi').type,'help');
assert.equal(aiIntent('perguntar '+ 'a'.repeat(451)).type,'help');
assert.equal(configured({}),false);
assert.equal(configured({IRIS_AI_ENABLED:'true',OPENAI_API_KEY:'sk-SyntheticTestKeyNeverReal'}),false);
assert.equal(likelyPrivate('meu email teste@example.com'),true);
assert.equal(safeModeration({results:[{flagged:false,categories:{violence:false}}]}),true);
assert.equal(safeModeration({results:[{flagged:true,categories:{violence:true}}]}),false);
let calls=0;
const env={IRIS_AI_ENABLED:'true',IRIS_AI_SUPERVISED_PILOT_APPROVED:'true',OPENAI_API_KEY:'sk-SyntheticTestKeyNeverReal'};
assert.equal(configIssue({...env,OPENAI_API_KEY:'PENDENTE_CONFIGURACAO'}),'key_missing');
assert.equal(configIssue({...env,OPENAI_API_KEY:'bad'}),'key_format');
assert.equal(configIssue({...env,OPENAI_API_KEY:' '+env.OPENAI_API_KEY+'\n'}),'ready');
assert.equal(configIssue({...env,IRIS_AI_SUPERVISED_PILOT_APPROVED:'false'}),'approval_missing');
const ai=createAI({env,fetcher:async(url,opts)=>{
    calls++;
    const b=JSON.parse(opts.body);
    if(url.endsWith('/moderations'))return {ok:true,json:async()=>({results:[{flagged:false,categories:{violence:false,sexual:false}}]})};
    assert.equal(url,'https://api.openai.com/v1/responses');
    assert.equal(b.store,false);
    assert.equal(b.input,'Por que o céu é azul?');
    assert.equal(b.model,'gpt-6.2-sol');
    assert.equal(typeof b.safety_identifier,'string');
    assert.equal(b.tools,undefined);
    return {ok:true,json:async()=>({status:'completed',output:[{type:'message',role:'assistant',content:[{type:'output_text',text:'Por causa da dispersão da luz.'}]}]})};
}});
assert.match(await ai({arg:'perguntar teste',actor:'test',owner:false}),/restrito/);
assert.equal(calls,0);
assert.match(await ai({arg:'perguntar teste@example.com',actor:'test',owner:true}),/Remova/);
assert.equal(calls,0);
assert.match(await ai({arg:'perguntar Por que o céu é azul?',actor:'test',owner:true}),/dispersão/);
assert.equal(calls,3);
const blocked=createAI({env,fetcher:async()=>({ok:true,json:async()=>({results:[{flagged:true,categories:{violence:true}}]})})});
assert.match(await blocked({arg:'perguntar teste',actor:'test',owner:true}),/Não posso/);
const disabled=createAI({env:{},fetcher:async()=>{throw Error('Unexpected network');}});
assert.match(await disabled({arg:'perguntar teste',actor:'test',owner:true}),/desativada/);
assert.equal(parseExtra('!iris ia status',true).name,'ia');
console.log('Iris: supervised OpenAI pilot mock tests passed');
