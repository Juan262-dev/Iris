import assert from 'node:assert/strict';
import {EventEmitter} from 'node:events';
import {makeSupervisor} from './managerSupervisor.js';
import {relinkNumber} from '../lib/Initialize/cloudAuth.js';
assert.equal(relinkNumber({registered:true,me:{id:'5511999999999:4@s.whatsapp.net'}}),'5511999999999');
assert.equal(relinkNumber({registered:true,me:{id:'12345678901234@lid'}}),null);
assert.equal(relinkNumber({registered:false,me:{id:'5511999999999@s.whatsapp.net'}}),null);
const children=[];
const sup=makeSupervisor({initial:async()=>true,persist:async()=>{},spawn:opts=>{const c=new EventEmitter();c.send=m=>{assert.equal(m.type,'stop');queueMicrotask(()=>c.emit('exit'));};children.push({c,opts});return c;}});
await sup.boot();children[0].c.emit('message',{type:'status',status:'conectado',storage:'ok'});
await assert.rejects(sup.relink('owner'));
children[0].c.emit('message',{type:'status',status:'desconectado'});
await sup.relink('owner');assert.equal(children[1].opts.relink,true);
children[1].c.emit('message',{type:'pairing-code',code:'TEST1234'});
assert.equal(sup.pairingStatus('owner').code,'TEST1234');
assert.equal(sup.pairingStatus('other').code,null);
assert.equal(JSON.stringify(sup.snapshot()).includes('TEST1234'),false);
children[1].c.emit('message',{type:'pairing-clear'});
assert.equal(sup.pairingStatus('owner').code,null);
await sup.shutdown();
console.log('Iris: same-account relink, isolated pairing secret and connected-session protection tests passed');
