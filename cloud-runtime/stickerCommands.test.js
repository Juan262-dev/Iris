import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import * as baileys from '@whiskeysockets/baileys';
import { selectMedia,withStickerAudio,stickerCommand } from './stickerCommands.js';
import { videoToSticker } from './advancedMedia.js';
import { parseExtra } from './features.js';
import { execFileSync } from 'node:child_process';
import { mkdtemp,readFile,rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import sharp from 'sharp';
const group='test@g.us';
const clip={mimetype:'video/mp4',seconds:20};
const quoted={key:{remoteJid:group},message:{extendedTextMessage:{text:'!iris slonga',contextInfo:{stanzaId:'test',quotedMessage:{videoMessage:clip}}}}};
assert.equal(selectMedia(quoted).message.videoMessage,clip);
assert.equal(selectMedia({...quoted,key:{remoteJid:'private@s.whatsapp.net'}}),null);
assert.equal(selectMedia({key:{remoteJid:group},message:{extendedTextMessage:{contextInfo:{stanzaId:'test',remoteJid:'other@g.us',quotedMessage:{videoMessage:clip}}}}}),null);
assert.equal(selectMedia({key:{remoteJid:group},message:{extendedTextMessage:{contextInfo:{stanzaId:'test',quotedMessage:{viewOnceMessageV2:{message:{videoMessage:clip}}}}}}}),null);
assert.equal(parseExtra('!iris som 20',false).name,'som');
assert.equal(parseExtra('!iris slonga',false).name,'slonga');
assert.equal(typeof baileys.prepareWAMessageMedia,'function');
const codec=baileys.proto.Message.StickerMessage, original=codec.encode;
const hash=createHash('sha256').update('test').digest();
const sticker={fileSha256:hash,isAnimated:true};
const ordinary=Buffer.from(codec.encode(sticker).finish());
const audio={mimetype:'audio/ogg; codecs=opus',seconds:2};
const audioBytes=Buffer.from(baileys.proto.Message.AudioMessage.encode(audio).finish());
const enhanced=await withStickerAudio(baileys.proto,hash,audio,async()=>Buffer.from(codec.encode(sticker).finish()));
assert.ok(enhanced.length>ordinary.length);
assert.deepEqual(enhanced.subarray(0,ordinary.length),ordinary);
assert.deepEqual(enhanced.subarray(-audioBytes.length),audioBytes);
assert.equal(codec.encode,original);
await assert.rejects(()=>withStickerAudio(baileys.proto,hash,audio,async()=>{throw Error('simulated send failure')}));
assert.equal(codec.encode,original);
console.log('Iris: quoted media and isolated sound sticker protocol tests passed');
const dir=await mkdtemp(join(tmpdir(),'iris-long-test-'));
try{
    const file=join(dir,'sample.mp4');
    execFileSync('ffmpeg',['-hide_banner','-loglevel','error','-y','-f','lavfi','-i','testsrc2=size=64x64:rate=3','-f','lavfi','-i','sine=frequency=440:sample_rate=48000','-t','20','-c:v','mpeg4','-c:a','aac',file],{timeout:15000});
    const data=await readFile(file);
    const out=await videoToSticker(data,{seconds:20,sound:true});
    assert.equal(out.soundSticker.audio.toString('ascii',0,4),'OggS');
    const meta=await sharp(out.soundSticker.sticker,{animated:true,limitInputPixels:18000000}).metadata();
    const duration=meta.delay.reduce((a,b)=>a+b,0);
    assert.ok(duration>=19000&&duration<=20020);
    assert.ok(out.soundSticker.sticker.length<=450000);
    console.log('Iris: twenty-second animated sticker and Opus audio tests passed');
}finally{await rm(dir,{recursive:true,force:true});}
