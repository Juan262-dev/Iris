import assert from 'node:assert/strict';
import {createServer} from 'node:http';
import {makeWorldStorage,makePersistentWorld,privateWorldRecipient} from './worldPersistent.js';
import {makeWorldHttp,worldUrl} from './world-web.js';
const key=Buffer.alloc(32,7),rows=new Map(),config=sessionId=>({sessionId,key});
const query=async(s,method,body)=>{if(method==='GET')return rows.has(s.sessionId)?[rows.get(s.sessionId)]:[];if(method==='POST')rows.set(s.sessionId,{encrypted_payload:body.encrypted_payload});if(method==='DELETE')rows.delete(s.sessionId);};
const store=makeWorldStorage({config,query});
let now=10000000,member=true,profile=true;
const a={jid:'group-a@g.us',actor:'12345@lid',route:'12345@lid'},b={jid:a.jid,actor:'67890@lid',route:'67890@lid'};
const operate=async identity=>profile?{view:{xp:identity.actor===a.actor?7:9}}:null;
const options={store,clock:()=>now,verify:async()=>member,operate};
let world=makePersistentWorld(options);
const code=await world.issue(a),login=await world.rpc({op:'login',code});
assert.equal(login.status,200);assert.match(login.session,/^[a-f0-9]{112}$/);assert.equal(login.data.view.xp,7);
assert.equal((await world.rpc({op:'login',code})).status,401);
assert.ok([...rows.values()].every(r=>!JSON.stringify(r).includes(a.actor)&&!JSON.stringify(r).includes(login.session)));
now+=500*86400000;world=makePersistentWorld({...options,store:makeWorldStorage({config,query})});
assert.equal((await world.rpc({op:'state',session:login.session})).status,200);
assert.equal((await world.rpc({op:'state',session:login.session})).status,429);
const fake=login.session.slice(0,-1)+(login.session.endsWith('a')?'b':'a');
assert.equal((await world.rpc({op:'state',session:fake})).status,401);
const other=await world.rpc({op:'login',code:await world.issue(b)});assert.equal(other.data.view.xp,9);
const newer=await world.rpc({op:'login',code:await world.issue(a)});assert.equal((await world.rpc({op:'state',session:login.session})).status,401);
await world.cancel(a);now+=1100;assert.equal((await world.rpc({op:'state',session:newer.session})).status,200);
await world.revoke(a);assert.equal((await world.rpc({op:'state',session:newer.session})).status,401);
assert.equal((await world.rpc({op:'state',session:other.session})).status,200);
await world.revokeGroup(a.jid);assert.equal((await world.rpc({op:'state',session:other.session})).status,401);
const expired=await world.issue(a);now+=300001;assert.equal((await world.rpc({op:'login',code:expired})).status,401);
const memberLogin=await world.rpc({op:'login',code:await world.issue(a)});member=false;now+=1100;assert.equal((await world.rpc({op:'state',session:memberLogin.session})).status,403);member=true;
assert.equal((await world.rpc({op:'state',session:memberLogin.session})).status,401);
const profileLogin=await world.rpc({op:'login',code:await world.issue(a)});profile=false;now+=1100;assert.equal((await world.rpc({op:'state',session:profileLogin.session})).status,403);profile=true;
const normalize=v=>typeof v==='string'&&/^[0-9]+@(lid|s\.whatsapp\.net)$/.test(v)?v:null;
const participants=[{id:'12345@lid',phoneNumber:'11111@s.whatsapp.net'},{id:'67890@lid',phoneNumber:'22222@s.whatsapp.net'}];
assert.equal(privateWorldRecipient(participants,'12345@lid',normalize),'11111@s.whatsapp.net');
assert.equal(privateWorldRecipient(participants,'67890@lid',normalize),'22222@s.whatsapp.net');
assert.equal(privateWorldRecipient(participants,'99999@lid',normalize),null);
assert.equal(privateWorldRecipient([...participants,{id:'12345@lid'}],'12345@lid',normalize),null);
const http=makeWorldHttp({world:input=>world.rpc(input)}),server=createServer(async(req,res)=>{if(!await http(req,res)){res.writeHead(404);res.end();}});
await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));
const base='http://127.0.0.1:'+server.address().port,origin=new URL(worldUrl).origin;
const post=(op,body={},cookie='')=>fetch(base+'/world/api/'+op,{method:'POST',headers:{origin,'content-type':'application/json',cookie},body:JSON.stringify(body)});
try{
 const linked=await post('login',{code:await world.issue(a)});assert.equal(linked.status,200);
 const cookie=linked.headers.get('set-cookie');assert.match(cookie,/Max-Age=34560000/);assert.match(cookie,/HttpOnly/);assert.match(cookie,/SameSite=Strict/);assert.match(cookie,/Secure/);assert.equal((await linked.json()).session,undefined);
 const jar=cookie.split(';')[0];now+=1100;world=makePersistentWorld(options);
 const restored=await post('state',{},jar);assert.equal(restored.status,200);assert.match(restored.headers.get('set-cookie'),/Max-Age=34560000/);
 const logout=await post('logout',{},jar);assert.equal(logout.status,200);assert.match(logout.headers.get('set-cookie'),/Max-Age=0/);
 assert.equal((await post('state',{},jar)).status,401);
}finally{await new Promise(resolve=>server.close(resolve));}
console.log('Iris: persistent World login, restart recovery, private recipient isolation, token rotation, revocation and renewed cookies tests passed');
